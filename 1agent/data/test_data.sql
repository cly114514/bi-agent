-- bi-agent 复杂测试数据 SQL (10x+ 复杂度)
-- 模拟真实企业 BI 场景：销售、供应链、用户行为、财务、客服

DROP TABLE IF EXISTS customers;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS categories;
DROP TABLE IF EXISTS stores;
DROP TABLE IF EXISTS suppliers;
DROP TABLE IF EXISTS inventory;
DROP TABLE IF EXISTS shipments;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS user_activity;
DROP TABLE IF EXISTS marketing_campaigns;
DROP TABLE IF EXISTS ads_clicklog;
DROP TABLE IF EXISTS tickets;
DROP TABLE IF EXISTS employees;
DROP TABLE IF EXISTS departments;
DROP TABLE IF EXISTS monthly_targets;
DROP TABLE IF EXISTS daily_sales;

-- ═══════════════════════════════════════════════════════════════
-- 1. 客户表 (customers)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE customers (
    customer_id VARCHAR(20) PRIMARY KEY COMMENT '客户ID',
    customer_name VARCHAR(100) COMMENT '客户名称',
    region VARCHAR(50) COMMENT '地区',
    city VARCHAR(50) COMMENT '城市',
    industry VARCHAR(50) COMMENT '所属行业',
    customer_level ENUM('A', 'B', 'C', 'D') COMMENT '客户等级',
    registration_date DATE COMMENT '注册日期',
    annual_revenue DECIMAL(15,2) COMMENT '年营收',
    employee_count INT COMMENT '员工规模',
    credit_score INT COMMENT '信用评分(300-850)',
    is_active TINYINT COMMENT '是否活跃',
    last_order_date DATE COMMENT '最近下单日期',
    channel VARCHAR(30) COMMENT '获客渠道'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 2. 门店表 (stores)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE stores (
    store_id VARCHAR(20) PRIMARY KEY COMMENT '门店ID',
    store_name VARCHAR(100) COMMENT '门店名称',
    region VARCHAR(50) COMMENT '地区',
    city VARCHAR(50) COMMENT '城市',
    store_type ENUM('直营', '加盟', '联营') COMMENT '门店类型',
    area_sqm DECIMAL(10,2) COMMENT '面积(平方米)',
    rent_monthly DECIMAL(12,2) COMMENT '月租金',
    staff_count INT COMMENT '员工数',
    opening_date DATE COMMENT '开业日期',
    operation_years INT COMMENT '运营年数',
    store_level ENUM('旗舰店', '标准店', '社区店') COMMENT '门店等级'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 3. 供应商表 (suppliers)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE suppliers (
    supplier_id VARCHAR(20) PRIMARY KEY COMMENT '供应商ID',
    supplier_name VARCHAR(100) COMMENT '供应商名称',
    region VARCHAR(50) COMMENT '地区',
    category VARCHAR(50) COMMENT '供应品类',
    supplier_level ENUM('战略', '核心', '普通', '潜在') COMMENT '供应商等级',
    on_time_rate DECIMAL(5,2) COMMENT '准时交货率',
    quality_score DECIMAL(5,2) COMMENT '质量评分',
    lead_time_days INT COMMENT '交货周期(天)',
    min_order_qty INT COMMENT '最小订货量',
    payment_terms VARCHAR(30) COMMENT '付款条款',
    is_active TINYINT COMMENT '是否合作中'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 4. 产品分类表 (categories)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE categories (
    category_id VARCHAR(20) PRIMARY KEY COMMENT '分类ID',
    category_name VARCHAR(50) COMMENT '分类名称',
    parent_category VARCHAR(50) COMMENT '上级分类',
    margin_target DECIMAL(5,2) COMMENT '目标毛利率',
    sort_order INT COMMENT '排序'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 5. 产品表 (products)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE products (
    product_id VARCHAR(20) PRIMARY KEY COMMENT '产品ID',
    product_name VARCHAR(100) COMMENT '产品名称',
    category_id VARCHAR(20) COMMENT '分类ID',
    supplier_id VARCHAR(20) COMMENT '供应商ID',
    unit_cost DECIMAL(10,2) COMMENT '单位成本',
    unit_price DECIMAL(10,2) COMMENT '单位售价',
    stock_quantity INT COMMENT '库存数量',
    reorder_point INT COMMENT '再订货点',
    product_status ENUM('在售', '停售', '预售', '缺货') COMMENT '产品状态',
    weight_kg DECIMAL(8,3) COMMENT '重量(kg)',
    shelf_life_days INT COMMENT '保质期(天)',
    is_vip_only TINYINT COMMENT '是否VIP专供',
    launch_date DATE COMMENT '上市日期'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 6. 订单主表 (orders)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE orders (
    order_id VARCHAR(30) PRIMARY KEY COMMENT '订单ID',
    customer_id VARCHAR(20) COMMENT '客户ID',
    store_id VARCHAR(20) COMMENT '门店ID',
    order_date DATETIME COMMENT '下单时间',
    shipment_date DATE COMMENT '发货日期',
    delivery_date DATE COMMENT '收货日期',
    order_type ENUM('线上', '线下', '批发', '团购') COMMENT '订单类型',
    order_status ENUM('待付款', '已付款', '已发货', '已收货', '已完成', '已取消', '退款中', '已退款') COMMENT '订单状态',
    payment_method ENUM('微信支付', '支付宝', '银行卡', '现金', '企业转账', '月结') COMMENT '支付方式',
    total_amount DECIMAL(12,2) COMMENT '订单总额',
    discount_amount DECIMAL(10,2) COMMENT '优惠金额',
    freight DECIMAL(10,2) COMMENT '运费',
    is_installed TINYINT COMMENT '是否需要安装',
    installation_date DATE COMMENT '安装日期',
    salesperson VARCHAR(50) COMMENT '负责销售',
    region VARCHAR(50) COMMENT '地区',
    city VARCHAR(50) COMMENT '城市'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 7. 订单明细表 (order_items)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE order_items (
    item_id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '明细ID',
    order_id VARCHAR(30) COMMENT '订单ID',
    product_id VARCHAR(20) COMMENT '产品ID',
    quantity INT COMMENT '数量',
    unit_price DECIMAL(10,2) COMMENT '单价',
    discount_rate DECIMAL(5,2) COMMENT '折扣率',
    item_amount DECIMAL(12,2) COMMENT '明细金额',
    is_returned TINYINT COMMENT '是否退货',
    return_reason VARCHAR(100) COMMENT '退货原因'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 8. 库存表 (inventory)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE inventory (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    store_id VARCHAR(20) COMMENT '门店ID',
    product_id VARCHAR(20) COMMENT '产品ID',
    warehouse_type ENUM('门店仓', '中心仓', '周转仓') COMMENT '仓库类型',
    stock_date DATE COMMENT '库存日期',
    opening_stock INT COMMENT '期初库存',
    in_stock INT COMMENT '入库数量',
    out_stock INT COMMENT '出库数量',
    closing_stock INT COMMENT '期末库存',
    stock_value DECIMAL(15,2) COMMENT '库存金额',
    turnover_rate DECIMAL(6,3) COMMENT '周转率'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 9. 物流表 (shipments)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE shipments (
    shipment_id VARCHAR(30) PRIMARY KEY COMMENT '发货单ID',
    order_id VARCHAR(30) COMMENT '订单ID',
    supplier_id VARCHAR(20) COMMENT '供应商ID',
    shipment_date DATE COMMENT '发货日期',
    expected_date DATE COMMENT '预计到货日期',
    actual_date DATE COMMENT '实际到货日期',
    logistics_provider VARCHAR(50) COMMENT '物流商',
    tracking_no VARCHAR(50) COMMENT '运单号',
    shipping_cost DECIMAL(10,2) COMMENT '运费',
    delivery_days INT COMMENT '配送时长(天)',
    is_on_time TINYINT COMMENT '是否准时',
    damage_count INT COMMENT '破损数量',
    shipment_status ENUM('待发货', '运输中', '已到达', '已签收', '异常') COMMENT '发货状态'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 10. 用户表 (users)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE users (
    user_id VARCHAR(20) PRIMARY KEY COMMENT '用户ID',
    nickname VARCHAR(50) COMMENT '昵称',
    mobile VARCHAR(20) COMMENT '手机号',
    gender ENUM('男', '女', '未知') COMMENT '性别',
    age_group ENUM('18以下', '18-25', '26-35', '36-45', '46-55', '55以上') COMMENT '年龄段',
    city VARCHAR(50) COMMENT '城市',
    user_level ENUM('VIP', '黄金', '白银', '普通') COMMENT '用户等级',
    registration_date DATETIME COMMENT '注册日期',
    first_order_date DATE COMMENT '首单日期',
    first_order_amount DECIMAL(10,2) COMMENT '首单金额',
    total_orders INT COMMENT '累计订单数',
    total_amount DECIMAL(15,2) COMMENT '累计消费金额',
    avg_order_amount DECIMAL(10,2) COMMENT '平均客单价',
    last_login_date DATETIME COMMENT '最近登录',
    last_order_date DATE COMMENT '最近下单',
    days_since_last_login INT COMMENT '距最近登录天数',
    points_balance INT COMMENT '积分余额',
    is_subscribed TINYINT COMMENT '是否订阅短信'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 11. 用户行为表 (user_activity)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE user_activity (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id VARCHAR(20) COMMENT '用户ID',
    activity_date DATE COMMENT '活动日期',
    page_views INT COMMENT '页面浏览量',
    sessions INT COMMENT '会话数',
    duration_seconds INT COMMENT '停留时长(秒)',
    bounce_rate DECIMAL(5,2) COMMENT '跳出率',
    cart_actions INT COMMENT '加购次数',
    wishlist_items INT COMMENT '收藏数',
    checkout_attempts INT COMMENT '结算尝试次数',
    platform ENUM('APP', '小程序', 'PC网站', 'H5') COMMENT '平台'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 12. 营销活动表 (marketing_campaigns)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE marketing_campaigns (
    campaign_id VARCHAR(20) PRIMARY KEY COMMENT '活动ID',
    campaign_name VARCHAR(100) COMMENT '活动名称',
    campaign_type ENUM('满减', '折扣', '赠品', '返现', '秒杀', '拼团', '抽奖') COMMENT '活动类型',
    start_date DATE COMMENT '开始日期',
    end_date DATE COMMENT '结束日期',
    budget DECIMAL(12,2) COMMENT '预算',
    actual_cost DECIMAL(12,2) COMMENT '实际成本',
    impressions INT COMMENT '曝光量',
    clicks INT COMMENT '点击量',
    orders INT COMMENT '转化订单数',
    sales_amount DECIMAL(15,2) COMMENT '销售金额',
    roi DECIMAL(8,3) COMMENT '投资回报率',
    coupon_used INT COMMENT '优惠券使用数',
    campaign_status ENUM('计划中', '进行中', '已结束', '已暂停') COMMENT '活动状态'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 13. 广告点击日志 (ads_clicklog)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE ads_clicklog (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    click_date DATE COMMENT '日期',
    campaign_id VARCHAR(20) COMMENT '活动ID',
    channel ENUM('抖音', '微信朋友圈', '百度', '小红书', '微博', 'B站') COMMENT '渠道',
    ad_position VARCHAR(50) COMMENT '广告位置',
    impressions INT COMMENT '展示次数',
    clicks INT COMMENT '点击次数',
    ctr DECIMAL(6,4) COMMENT '点击率',
    cpc DECIMAL(8,2) COMMENT '点击成本',
    spend DECIMAL(10,2) COMMENT '消耗金额',
    conversions INT COMMENT '转化数',
    conversion_rate DECIMAL(6,4) COMMENT '转化率',
    revenue DECIMAL(12,2) COMMENT '带来的收入'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 14. 客服工单表 (tickets)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE tickets (
    ticket_id VARCHAR(20) PRIMARY KEY COMMENT '工单ID',
    user_id VARCHAR(20) COMMENT '用户ID',
    order_id VARCHAR(30) COMMENT '订单ID',
    category ENUM('物流问题', '商品质量', '退款申请', '售后维修', '投诉建议', '其他') COMMENT '问题类型',
    priority ENUM('紧急', '高', '中', '低') COMMENT '优先级',
    status ENUM('待处理', '处理中', '已解决', '已关闭', '升级') COMMENT '工单状态',
    created_date DATETIME COMMENT '创建时间',
    assigned_to VARCHAR(50) COMMENT '处理人',
    response_time_hours DECIMAL(8,2) COMMENT '响应时长(小时)',
    resolution_time_hours DECIMAL(8,2) COMMENT '解决时长(小时)',
    satisfaction_score INT COMMENT '满意度评分(1-5)',
    is_first_response TINYINT COMMENT '是否首次响应及时'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 15. 部门表 (departments)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE departments (
    dept_id VARCHAR(20) PRIMARY KEY COMMENT '部门ID',
    dept_name VARCHAR(50) COMMENT '部门名称',
    parent_dept VARCHAR(20) COMMENT '上级部门',
    dept_type ENUM('销售', '运营', '技术', '职能', '仓配') COMMENT '部门类型',
    employee_count INT COMMENT '员工数',
    budget_annual DECIMAL(15,2) COMMENT '年度预算'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 16. 员工表 (employees)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE employees (
    emp_id VARCHAR(20) PRIMARY KEY COMMENT '员工ID',
    emp_name VARCHAR(50) COMMENT '员工姓名',
    dept_id VARCHAR(20) COMMENT '部门ID',
    position VARCHAR(50) COMMENT '职位',
    gender ENUM('男', '女') COMMENT '性别',
    age INT COMMENT '年龄',
    education VARCHAR(20) COMMENT '学历',
    hire_date DATE COMMENT '入职日期',
    base_salary DECIMAL(10,2) COMMENT '基本工资',
    bonus DECIMAL(10,2) COMMENT '奖金',
    performance_score DECIMAL(4,2) COMMENT '绩效评分',
    is_on_job TINYINT COMMENT '是否在职'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 17. 月度目标表 (monthly_targets)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE monthly_targets (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    month VARCHAR(7) COMMENT '月份(YYYY-MM)',
    region VARCHAR(50) COMMENT '地区',
    dept_id VARCHAR(20) COMMENT '部门ID',
    salesperson VARCHAR(50) COMMENT '销售员',
    target_sales DECIMAL(15,2) COMMENT '销售目标',
    actual_sales DECIMAL(15,2) COMMENT '实际销售',
    target_orders INT COMMENT '订单目标',
    actual_orders INT COMMENT '实际订单',
    completion_rate DECIMAL(6,3) COMMENT '完成率',
    target_margin DECIMAL(5,2) COMMENT '毛利率目标',
    actual_margin DECIMAL(5,2) COMMENT '实际毛利率',
    ranking INT COMMENT '排名'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ═══════════════════════════════════════════════════════════════
-- 18. 每日销售表 (daily_sales)
-- ═══════════════════════════════════════════════════════════════
CREATE TABLE daily_sales (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    sale_date DATE COMMENT '销售日期',
    region VARCHAR(50) COMMENT '地区',
    store_id VARCHAR(20) COMMENT '门店ID',
    category_id VARCHAR(20) COMMENT '分类ID',
    product_id VARCHAR(20) COMMENT '产品ID',
    sales_amount DECIMAL(12,2) COMMENT '销售额',
    sales_quantity INT COMMENT '销售数量',
    profit_amount DECIMAL(12,2) COMMENT '利润额',
    gross_margin DECIMAL(6,3) COMMENT '毛利率',
    return_amount DECIMAL(10,2) COMMENT '退货额',
    return_rate DECIMAL(6,4) COMMENT '退货率',
    customer_count INT COMMENT '客户数',
    avg_unit_price DECIMAL(10,2) COMMENT '平均单价'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

