-- 生成订单明细 (每订单1-5条明细)
-- ═══════════════════════════════════════════════════════════════
INSERT INTO order_items (order_id, product_id, quantity, unit_price, discount_rate, item_amount, is_returned, return_reason)
SELECT
    o.order_id,
    CONCAT('P', LPAD(1 + (ROW_NUMBER() OVER (PARTITION BY o.order_id)) % 60, 3, '0')) AS product_id,
    1 + (ROW_NUMBER() OVER (PARTITION BY o.order_id)) % 4 AS quantity,
    ROUND(200 + RAND() * 8000, 2) AS unit_price,
    ROUND(0.85 + RAND() * 0.15, 2) AS discount_rate,
    ROUND((200 + RAND() * 8000) * (1 + (ROW_NUMBER() OVER (PARTITION BY o.order_id)) % 4)) * (0.85 + RAND() * 0.15), 2) AS item_amount,
    IF(RAND() > 0.92, 1, 0) AS is_returned,
    IF(RAND() > 0.92, ELT(1 + FLOOR(RAND() * 5), '七天无理由', '商品损坏', '型号错误', '未收到货', '其他'), NULL) AS return_reason
FROM orders o
CROSS JOIN (
    SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4 UNION SELECT 5
) item_nums
WHERE (SELECT COUNT(*) FROM orders) > 0;

