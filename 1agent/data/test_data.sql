-- 生成订单主表数据 (200条循环生成)
-- ═══════════════════════════════════════════════════════════════
INSERT INTO orders (order_id, customer_id, store_id, order_date, shipment_date, delivery_date, order_type, order_status, payment_method, total_amount, discount_amount, freight, is_installed, installation_date, salesperson, region, city)
SELECT
    CONCAT('ORD', DATE_FORMAT(order_date, '%Y%m%d'), LPAD(ROW_NUMBER() OVER (PARTITION BY DATE(order_date)), 4, '0')) AS order_id,
    CONCAT('C0', 1 + (ROW_NUMBER() OVER (ORDER BY order_date) % 80)) AS customer_id,
    CONCAT('S0', 1 + (ROW_NUMBER() OVER (ORDER BY order_date) % 45)) AS store_id,
    order_date,
    DATE_ADD(order_date, INTERVAL 1 DAY) AS shipment_date,
    DATE_ADD(order_date, INTERVAL 3 DAY) AS delivery_date,
    ELT(1 + (ROW_NUMBER() OVER (ORDER BY order_date) % 4), '线上', '线下', '批发', '团购') AS order_type,
    ELT(1 + (ROW_NUMBER() OVER (ORDER BY order_date) % 8), '待付款', '已付款', '已发货', '已收货', '已完成', '已取消', '退款中', '已退款') AS order_status,
    ELT(1 + (ROW_NUMBER() OVER (ORDER BY order_date) % 6), '微信支付', '支付宝', '银行卡', '现金', '企业转账', '月结') AS payment_method,
    ROUND(500 + RAND() * 9500, 2) AS total_amount,
    ROUND(RAND() * 300, 2) AS discount_amount,
    ROUND(10 + RAND() * 90, 2) AS freight,
    IF(RAND() > 0.8, 1, 0) AS is_installed,
    IF(RAND() > 0.8, DATE_ADD(order_date, INTERVAL 5 DAY), NULL) AS installation_date,
    CONCAT('销售员', 1 + (ROW_NUMBER() OVER (ORDER BY order_date) % 20)) AS salesperson,
    ELT(1 + (ROW_NUMBER() OVER (ORDER BY order_date) % 6), '华东', '华南', '华北', '华中', '西南', '东北') AS region,
    ELT(1 + (ROW_NUMBER() OVER (ORDER BY order_date) % 10), '杭州', '上海', '深圳', '广州', '北京', '天津', '武汉', '成都', '重庆', '沈阳') AS city
FROM (
    SELECT DATE_ADD('2025-01-01', INTERVAL n DAY) AS order_date
    FROM (
        SELECT @row := @row + 1 AS n FROM
        (SELECT 0 UNION SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4 UNION SELECT 5 UNION SELECT 6 UNION SELECT 7 UNION SELECT 8 UNION SELECT 9) t1,
        (SELECT 0 UNION SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4 UNION SELECT 5 UNION SELECT 6 UNION SELECT 7 UNION SELECT 8 UNION SELECT 9) t2,
        (SELECT 0 UNION SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4) t3,
        (SELECT @row := -1) r
    ) numbers
    WHERE n < 147
) dates;

